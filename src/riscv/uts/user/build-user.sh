#!/usr/bin/env bash
# build-user.sh — build the solnix riscv64 userland ELFs (init, sh, hello,
# echo, cat) and emit them as one embeddable C header (user_elfs.h) for the
# kernel to serve via the rootfs vfs and load via exec (R-P8).
#
# Each program is static, freestanding, no libc (shared libu.h ecall stubs),
# linked low (0xC0010000) as ET_EXEC so the kernel ELF loader (elf.c) maps its
# PT_LOAD into a fresh user address space. Each is its OWN address space at run
# time, so they all link at the same base with no conflict.
#
# Run via run-build.sh (enters the riscv64 cross toolchain nix shell) or with
# the toolchain already in PATH.
set -euo pipefail
cd "$(dirname "$0")"

TC="${TC:-riscv64-none-elf}"
CC="${CC:-${TC}-gcc}"
LD="${LD:-${TC}-ld}"
OBJDUMP="${OBJDUMP:-${TC}-objdump}"

CFLAGS="-march=rv64imac_zicsr -mabi=lp64 -mcmodel=medany \
	-ffreestanding -nostdlib -fno-stack-protector -fno-pic \
	-Wall -Wextra -Os -g"

PROGS="init sh hello echo cat"

echo "== build userland ELFs: $PROGS =="
for p in $PROGS; do
	"$CC" $CFLAGS -c "$p.c" -o "$p.o"
	"$LD" -T init.ld -o "$p.elf" "$p.o"
	echo "  $p.elf: $("$OBJDUMP" -f "$p.elf" | grep -o 'EXEC\|EM_RISCV\|riscv' | tr '\n' ' ')($(wc -c < "$p.elf") bytes)"
done

echo "== emit user_elfs.h =="
{
	echo "/*"
	echo " * user_elfs.h — GENERATED by user/build-user.sh. The static riscv64"
	echo " * userland ELFs (init, sh, hello, echo, cat) as byte arrays, embedded"
	echo " * in the kernel image so rootfs can serve them and exec can load them"
	echo " * (R-P8). Do not edit by hand; regenerate with user/build-user.sh."
	echo " */"
	echo "#ifndef _USER_ELFS_H"
	echo "#define _USER_ELFS_H"
	for p in $PROGS; do
		echo "static const unsigned char ${p}_elf[] = {"
		od -An -v -tu1 "$p.elf" | awk '{for(i=1;i<=NF;i++)printf "%s,",$i; print ""}'
		echo "};"
		echo "static const unsigned long ${p}_elf_len = sizeof (${p}_elf);"
	done
	echo "#endif /* _USER_ELFS_H */"
} > ../user_elfs.h

echo "== user_elfs.h written =="
ls -l ../user_elfs.h
