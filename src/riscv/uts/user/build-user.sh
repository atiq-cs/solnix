#!/usr/bin/env bash
# build-user.sh — build the solnix riscv64 userland: the libc slice
# (libc-riscv.a) + the programs (init, sh, hello, echo, cat) linked against it,
# then emit them as one embeddable C header (user_elfs.h) AND build the on-disk
# ustar rootfs image (adding /etc/motd + /etc/inittab, the SMF-style service
# list init reads at boot).
#
# R-P10: unlike the R-P9 header-only libu.h, each program now links against a
# REAL archive (libc-riscv.a): one crt0 (_start), one set of syscall stubs,
# malloc-over-brk, string + a real printf. This is the first libc on illumos-
# RISC-V.
#
# Each program is static, freestanding, no host libc, linked low (0xC0010000)
# as ET_EXEC so the kernel ELF loader maps its PT_LOAD into a fresh user AS.
set -euo pipefail
cd "$(dirname "$0")"

TC="${TC:-riscv64-none-elf}"
CC="${CC:-${TC}-gcc}"
LD="${LD:-${TC}-ld}"
AR="${AR:-${TC}-ar}"
OBJDUMP="${OBJDUMP:-${TC}-objdump}"

CFLAGS="-march=rv64imac_zicsr -mabi=lp64 -mcmodel=medany \
	-ffreestanding -nostdlib -fno-stack-protector -fno-pic \
	-Wall -Wextra -Os -g"

PROGS="init sh hello echo cat fbtest socktest polltest porttest miniwl"

# fptest is the ONE userland program built HARD-FLOAT (lp64d). Everything else is
# soft-float, which is exactly why the missing FP context-switch stayed hidden --
# no process ever used the FPU. This probe must use it to test it.
FP_CFLAGS="-march=rv64imafdc_zicsr -mabi=lp64d -mcmodel=medany -ffreestanding \
	-fno-stack-protector -fno-pie -O2 -Wall"

echo "== build libc slice: libc-riscv.a =="
"$CC" $CFLAGS -c libc.c -o libc.o
"$AR" rcs libc-riscv.a libc.o
echo "  libc-riscv.a: $("$AR" t libc-riscv.a | tr '\n' ' ')($(wc -c < libc-riscv.a) bytes)"

echo "== build userland ELFs (linked against libc-riscv.a): $PROGS =="
# fptest is standalone (its own _start, inline-asm syscalls, no libc) AND
# hard-float, so it is built separately from the soft-float PROGS loop and linked
# without libc-riscv.a.
"$CC" $FP_CFLAGS -c fptest.c -o fptest.o
"$LD" -T init.ld -o fptest.elf fptest.o
echo "  fptest.elf: hard-float lp64d ($(wc -c < fptest.elf) bytes)"

for p in $PROGS; do
	"$CC" $CFLAGS -c "$p.c" -o "$p.o"
	# Link the program object + the libc archive; _start + printf/malloc/etc
	# are pulled from libc-riscv.a.
	"$LD" -T init.ld -o "$p.elf" "$p.o" libc-riscv.a
	echo "  $p.elf: $("$OBJDUMP" -f "$p.elf" | grep -o 'EXEC\|riscv' | tr '\n' ' ')($(wc -c < "$p.elf") bytes)"
done

echo "== emit user_elfs.h =="
{
	echo "/*"
	echo " * user_elfs.h — GENERATED by user/build-user.sh. The static riscv64"
	echo " * userland ELFs, each linked against the libc-riscv.a slice, as byte"
	echo " * arrays embedded in the kernel image so rootfs can serve them and exec"
	echo " * can load them. Do not edit by hand."
	echo " *"
	echo " * TOOLCHAIN PROVENANCE: produced by riscv64 cross GCC"
	echo " * $("$CC" -dumpversion). Pin that version when regenerating so the"
	echo " * artifact is reproducible."
	echo " *"
	echo " * The regeneration that once broke the miniwl gate is FIXED: the cause was a"
	echo " * trap-vector bug, not the compiler and not this artifact. _trap_entry left"
	echo " * the interrupted sp parked in sscratch for the whole of trap(), so any trap"
	echo " * taken while trap() ran was misclassified as a trap from U-mode and built"
	echo " * its frame on the USER stack. Regeneration only changed instruction counts,"
	echo " * i.e. the clock's phase against that window, so the committed blob was a"
	echo " * lucky phase rather than a correct kernel. See trap.S and"
	echo " * docs/riscv64-first-real-binary.md."
	echo " *"
	echo " * Always re-run the boot gate after regenerating, and judge by BOOT RATE"
	echo " * across several attempts rather than one pass. This blob is a BUILD OUTPUT"
	echo " * kept in git because the toolchain that made it is not guaranteed"
	echo " * available."
	echo " */"
	echo "#ifndef _USER_ELFS_H"
	echo "#define _USER_ELFS_H"
	for p in $PROGS fptest; do
		echo "static const unsigned char ${p}_elf[] = {"
		od -An -v -tu1 "$p.elf" | awk '{for(i=1;i<=NF;i++)printf "%s,",$i; print ""}'
		echo "};"
		echo "static const unsigned long ${p}_elf_len = sizeof (${p}_elf);"
	done
	echo "#endif /* _USER_ELFS_H */"
} > ../user_elfs.h

echo "== user_elfs.h written =="
ls -l ../user_elfs.h

# --- build the on-disk root FS image (ustar) from the SAME ELFs + config files.
# The kernel's rootfs.c ustar reader parses it off a second virtio-blk. We add
# /etc/motd (banner cat reads) and /etc/inittab (the SMF-style service list
# /sbin/init walks at boot to reach multi-user). ---
echo "== build rootfs.img (ustar root FS for vioblk) =="
STAGE="$(mktemp -d)"
mkdir -p "$STAGE/sbin" "$STAGE/bin" "$STAGE/etc"
cp init.elf  "$STAGE/sbin/init"
cp sh.elf    "$STAGE/bin/sh"
cp hello.elf "$STAGE/bin/hello"
cp echo.elf  "$STAGE/bin/echo"
cp cat.elf   "$STAGE/bin/cat"
# R-P64: the /dev/fb scanout-seam proof (init runs it as a boot gate).
cp fbtest.elf "$STAGE/bin/fbtest"
# The AF_UNIX + SCM_RIGHTS gate (init runs it as a boot gate).
cp socktest.elf "$STAGE/bin/socktest"
# The poll(2) + anonymous-mmap gate (init runs it as a boot gate).
cp polltest.elf "$STAGE/bin/polltest"
cp porttest.elf "$STAGE/bin/porttest"
cp miniwl.elf   "$STAGE/bin/miniwl"
cp fptest.elf   "$STAGE/bin/fptest"
printf 'solnix riscv64 - the first illumos on RISC-V. R-P11: signals, writable FS, passwd login, concurrent shells.\n' \
	> "$STAGE/etc/motd"
# /etc/passwd: R-P11 login reads uid/gid/shell from here.
cat > "$STAGE/etc/passwd" <<'EOF'
# solnix /etc/passwd - read by /sbin/init login (R-P11).
# name:passwd:uid:gid:gecos:home:shell
root:x:0:0:Super-User:/root:/bin/sh
operator:x:2:5:Operator:/:/bin/sh
EOF
# inittab: the SMF-style service list. wait:=run-once boot task; respawn:=daemon.
cat > "$STAGE/etc/inittab" <<'EOF'
# solnix /etc/inittab - SMF-style service list read by /sbin/init.
# format: action:path   (action = wait | respawn)
wait:/bin/hello
EOF
( cd "$STAGE" && tar --format=ustar -cf rootfs.tar \
    sbin/init bin/sh bin/hello bin/echo bin/cat bin/fbtest bin/socktest \
    bin/polltest bin/porttest bin/miniwl bin/fptest etc/motd etc/inittab etc/passwd )
cp "$STAGE/rootfs.tar" ../rootfs.img
sz=$(wc -c < ../rootfs.img)
pad=$(( (512 - (sz % 512)) % 512 ))
if [ "$pad" -ne 0 ]; then
	dd if=/dev/zero bs=1 count="$pad" >> ../rootfs.img 2>/dev/null
fi
rm -rf "$STAGE"
echo "  rootfs.img: $(wc -c < ../rootfs.img) bytes (ustar; +etc/motd +etc/inittab)"

# --- the real-libc program. newlibtest links against newlib (a different libc,
# hard-float, medlow, its own link base), so it keeps its own builder rather than
# joining the PROGS loop. Chaining it here is what makes THIS script a full
# regeneration: rootfs.c references newlibtest_elf[], so a run of build-user.sh
# alone leaves the kernel unable to compile. ---
echo "== build /bin/newlibtest (real newlib libc) =="
# Both scripts cd to their own directory, so this one is a plain sibling name.
bash ./build-newlibtest.sh
