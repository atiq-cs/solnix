#!/bin/sh
#
# genassym.sh -- extract the compiler-computed offsets from a cross-compiled
# genassym object (or its .s) into an assym.h header.
#
# The genassym.c inline-asm emits, into the .assym section, NUL-terminated
# strings of the form:  @ASSYM@ NAME VALUE
# where VALUE is the compiler's real struct offset/size (an immediate).  We
# read those out of the disassembled/stringified object and turn each into a
# `#define NAME VALUE`.  This is the freestanding illumos/BSD genassym pipeline:
# the compiler does the offsetof math; this script only reformats.
#
# usage: genassym.sh <readelf-or-strings-tool> <genassym.o> > assym.h
#
# We read the .s the compiler produced (simplest + toolchain-agnostic): the
# .asciz lines carry "@ASSYM@ NAME <imm>".  From a .s the immediate is the
# operand the compiler folded into the string via %0 -> a literal.

set -e

SRC="$1"			# the genassym .s (compiler output)

echo "/*"
echo " * assym.h -- GENERATED by genassym.sh from genassym.c."
echo " * Assembly-side view of the illumos riscv64 MD struct offsets."
echo " * Do not edit; regenerate via the R-P20 genassym unit."
echo " */"
echo "#ifndef\t_RISCV_ASSYM_H"
echo "#define\t_RISCV_ASSYM_H"
echo ""

# Pull "@ASSYM@ NAME VALUE" out of the .asciz strings in the .s and reformat.
# The compiler renders %0 for an "i" (immediate) constraint as a bare decimal.
grep '@ASSYM@' "$SRC" | \
  sed -e 's/.*@ASSYM@ //' -e 's/\\0.*//' -e 's/".*//' | \
  awk 'NF==2 { printf "#define\t%s\t%s\n", $1, $2 }'

echo ""
echo "#endif\t/* _RISCV_ASSYM_H */"
