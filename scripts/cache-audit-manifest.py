#!/usr/bin/env python3
"""cache-audit-manifest.py CLASSIFIED_TSV OUT_TSV -- removal/regeneration manifest from cache-audit-classify.py output.
NARINFO_DIR env (default /var/tmp/cacheaudit/meta/narinfo) supplies the nar URL per hash."""
import csv,sys,os
csv.field_size_limit(1<<30)
F,O=sys.argv[1],sys.argv[2]
rows=list(csv.DictReader(open(F),delimiter='\t'))
def url(h):
    p=os.path.join(os.environ.get('NARINFO_DIR','/var/tmp/cacheaudit/meta/narinfo'), h+'.narinfo')
    if not os.path.exists(p): return '-'
    for l in open(p):
        if l.startswith('URL: '): return l[5:].strip()
    return '-'
rdep={}
for r in rows:
    for x in r['refs'].split():
        if x[:32]!=r['hash']: rdep[x[:32]]=rdep.get(x[:32],0)+1
act={'drop':'REMOVE','regenerate':'REMOVE+REBUILD','resign':'RESIGN-NARINFO'}
order={'REMOVE':0,'REMOVE+REBUILD':1,'RESIGN-NARINFO':2}
with open(O,'w') as fo:
    fo.write("# Cache removal + regeneration manifest (READ-ONLY audit, 2026-10-04; nothing in the cache was changed).\n")
    fo.write("# Generated by scripts/cache-audit-classify.py; see AUDIT-cache-nix-correctness-20261004.md for definitions.\n")
    fo.write("# REMOVE          delete narinfo_key + nar_key (and torrent/<nar>.torrent); junk, do not rebuild.\n")
    fo.write("# REMOVE+REBUILD  delete narinfo_key + nar_key; rebuild from a pure derivation (yields a NEW hash), sign with 8UNr.\n")
    fo.write("# RESIGN-NARINFO  NAR bytes pass; replace the 5HAV Sig with an 8UNr Sig over the unchanged fingerprint, re-upload narinfo only.\n")
    fo.write("# Keys are relative to the served root (https://cache.solnix.io/<key> == B2 cache/<key>). rdeps = audited objects referencing this one.\n")
    fo.write("action\tclass\tarch\thash\tstorepath\tnarinfo_key\tnar_key\treasons\trdeps\tblocked_by\n")
    out=[(order[act[r['class']]], r['arch'], -rdep.get(r['hash'],0), r['hash'], r) for r in rows if r['class'] in act]
    for o,_,_,_,r in sorted(out, key=lambda t:t[:4]):
        a=act[r['class']]
        fo.write('\t'.join([a,r['class'],r['arch'],r['hash'],r['storepath'],r['hash']+'.narinfo',url(r['hash']),r['reasons'],str(rdep.get(r['hash'],0)),r['closure_blockers']])+'\n')
